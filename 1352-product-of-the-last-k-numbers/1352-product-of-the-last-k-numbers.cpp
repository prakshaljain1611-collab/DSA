class ProductOfNumbers {
public:
    vector<int>ans;
    ProductOfNumbers() {
        
    }
    
    void add(int num) {
        ans.push_back(num);
    }
    
    int getProduct(int k) {
        int mul=1;
        for(int i=ans.size()-k;i<ans.size();i++){
            mul*=ans[i];
        }
        return mul;
    }
};

